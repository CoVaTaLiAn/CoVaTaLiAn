"""
======================================================================
【問題名】: Otoshidama (お年玉)
【難易度】: ABC-C相当

【問題文】:
N 枚のお札（10000円、5000円、1000円）で合計 Y 円となる組み合わせ (x, y, z) を求める。
存在しない場合は -1 -1 -1 を出力する。

【制約】:
- 1 <= N <= 2000
- 1000 <= Y <= 2 * 10^7
======================================================================
"""

N, Y = map(int, input().split())

for x in range(N + 1):
  for y in range(N + 1 - x):
    z = N - x - y
    
    if 10000 * x + 5000 * y + 1000 * z == Y:
      print(x, y, z)
      exit()

print("-1 -1 -1")